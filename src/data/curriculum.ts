/** A linear chain within each phase, plus each phase's first exercise requiring the previous phase's last exercise. */
function computePrerequisiteIds(exerciseId: string): string[] {
  for (const group of PHASE_EXERCISE_GROUPS) {
    const sorted = [...group].sort((a, b) => a.sortOrder - b.sortOrder);
    const idx = sorted.findIndex((e) => e.id === exerciseId);
    if (idx === -1) continue;
    if (idx > 0) return [sorted[idx - 1].id];

    // First exercise of a phase: depends on the last exercise of the previous phase (if any).
    const groupIdx = PHASE_EXERCISE_GROUPS.indexOf(group);
    if (groupIdx === 0) return [];
    const prevGroup = [...PHASE_EXERCISE_GROUPS[groupIdx - 1]].sort((a, b) => b.sortOrder - a.sortOrder);
    return [prevGroup[0].id];
  }
  return [];
}

