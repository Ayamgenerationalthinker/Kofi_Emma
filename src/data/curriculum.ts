// Gospel Drum Coach — static curriculum content.
//
// This is the single source of truth for the 4-phase, 40-exercise
// curriculum. There is no database behind it: it is bundled into the app at
// build time and read-only at runtime. Everything that changes per user
// (progress, attempts, sessions) lives in LocalStorage — see
// `src/lib/localDb.ts`.

export type Limb = "R" | "L" | "K" | "H" | "HH" | "REST";

export interface OrchestrationStep {
  limb: string;
  voice: string;
}

export interface MetronomeEvent {
  position: number;
  limb: Limb;
  accent?: boolean;
}

export interface MetronomePattern {
  timeSignature: string;
  subdivision: string;
  events: MetronomeEvent[];
}

export interface CurriculumPhase {
  id: string;
  number: number;
  title: string;
  subtitle: string;
  description: string;
  sortOrder: number;
}

export interface CurriculumExercise {
  id: string;
  phaseId: string;
  phaseNumber: number;
  name: string;
  slug: string;
  description: string;
  purpose: string;
  category: string;
  timeSignature: string;
  subdivision: string;
  stickingPattern: string;
  orchestration: OrchestrationStep[];
  patternEvents: MetronomePattern;
  techniqueNotes: string;
  commonMistakes: string[];
  targetBpm: number;
  minimumBpm: number;
  maximumBpm: number;
  minimumAccuracy: number;
  requiredConsecutiveCleanAttempts: number;
  durationMinutes: number;
  difficulty: number;
  sortOrder: number;
  styleLabel: string;
  /** Exercise ids that must be MASTERED before this one unlocks. */
  prerequisiteIds: string[];
}

interface ExerciseDef {
  id: string;
  phaseNumber: number;
  name: string;
  slug: string;
  description: string;
  purpose: string;
  category: string;
  timeSignature: string;
  subdivision: string;
  stickingPattern: string;
  orchestration?: OrchestrationStep[];
  techniqueNotes: string;
  commonMistakes: string[];
  targetBpm: number;
  minimumBpm: number;
  maximumBpm: number;
  minimumAccuracy: number;
  requiredConsecutiveCleanAttempts: number;
  durationMinutes: number;
  difficulty: number;
  styleLabel: string;
  sortOrder: number;
  accentEvery?: number;
}

const DEFAULT_VOICE: Record<string, string> = {
  R: "Snare (right hand)",
  L: "Snare (left hand)",
  K: "Kick",
  H: "Hi-Hat",
  HH: "Hi-Hat (foot)",
  REST: "Rest",
};

function tokensOf(sticking: string): Limb[] {
  return sticking.split(" ").filter(Boolean) as Limb[];
}

function buildOrchestration(sticking: string, custom?: OrchestrationStep[]): OrchestrationStep[] {
  if (custom) return custom;
  return tokensOf(sticking).map((t) => ({ limb: t, voice: DEFAULT_VOICE[t] ?? t }));
}

function buildEvents(sticking: string, accentEvery = 4): MetronomeEvent[] {
  return tokensOf(sticking).map((limb, i) => ({
    position: i,
    limb,
    accent: i % accentEvery === 0,
  }));
}

