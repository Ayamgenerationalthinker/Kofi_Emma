export function getExercise(id: string): CurriculumExercise | undefined {
  return EXERCISES.find((e) => e.id === id);
}

export function getPhase(id: string): CurriculumPhase | undefined {
  return PHASES.find((p) => p.id === id);
}

export function exercisesForPhase(phaseId: string): CurriculumExercise[] {
  return EXERCISES.filter((e) => e.phaseId === phaseId).sort((a, b) => a.sortOrder - b.sortOrder);
}
